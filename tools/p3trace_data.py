# Practical 3 branching maps (made by Claude). Node = (name, kind, note, [children]).
# kind: a artery · v vein (drains toward its parent) · n nerve · l lymph · s structure/space · d duct · f flow step
# Built from Bethany's bold-term lists + course-slide notes + lab guide; "(not bold)" marks connector names.
def N(name,kind,note='',*kids): return (name,kind,note,list(kids))
A=lambda n,note='',*k: N(n,'a',note,*k)
Vn=lambda n,note='',*k: N(n,'v',note,*k)
Nv=lambda n,note='',*k: N(n,'n',note,*k)
L=lambda n,note='',*k: N(n,'l',note,*k)
S=lambda n,note='',*k: N(n,'s',note,*k)
D=lambda n,note='',*k: N(n,'d',note,*k)
F=lambda n,note='',*k: N(n,'f',note,*k)
def chain(kind,steps):
    """linear route → nested single-child tree"""
    node=None
    for name,note in reversed(steps): node=N(name,kind,note,*([node] if node else []))
    return node

